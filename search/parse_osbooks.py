"""Parser for openstax/osbooks-calculus-bundle CNXML.

Source layout:
  modules/<module_id>/index.cnxml   e.g. modules/m53472/index.cnxml
  collections/<book>.collection.xml  book order / titles
  media/                             images (skipped, captions kept)

CNXML namespaces:
  default http://cnx.rice.edu/cnxml  -> document/title/content/para/section/equation/figure
  m http://www.w3.org/1998/Math/MathML -> math (linearized to text)
  md http://cnx.rice.edu/mdml        -> metadata (content-id, title, uuid)

Output: list[Chunk] with source="osbooks".
"""

from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET

from .chunk import MAX_CHARS, OVERLAP, EquationSpan, chunk_text, pack_blocks
from .schemas import Chunk

CNXML_NS = "http://cnx.rice.edu/cnxml"
MATH_NS = "http://www.w3.org/1998/Math/MathML"
MD_NS = "http://cnx.rice.edu/mdml"


def _local(tag: str) -> str:
    return tag.split("}", 1)[1] if "}" in tag else tag


MATH_TAG = "{" + MATH_NS + "}math"
_SIMPLE = re.compile(r"^[A-Za-z0-9.]+$")
_PRIME_CHARS = "\u2032\u2033\u2034'"  # prime, double prime, triple prime, apostrophe


def _is_wrapped(s: str) -> bool:
    """True if s is one parenthesised group, e.g. "(t/4)" but not "(a)+(b)"."""
    if not (s.startswith("(") and s.endswith(")")):
        return False
    depth = 0
    for i, ch in enumerate(s):
        depth += (ch == "(") - (ch == ")")
        if depth == 0 and i < len(s) - 1:
            return False
    return True


def _unwrap_presentation(el: ET.Element) -> ET.Element:
    while _local(el.tag) in {"mrow", "mstyle", "mpadded"} and len(el) == 1:
        el = el[0]
    return el


def _wrap(el: ET.Element, s: str) -> str:
    """Keep atomic identifiers/numbers bare; group compound MathML operands."""
    el = _unwrap_presentation(el)
    atomic = _local(el.tag) in {"mi", "mn"} and _SIMPLE.fullmatch(s)
    return s if atomic or _is_wrapped(s) else f"({s})"


def _is_frac(el: ET.Element) -> bool:
    """A fraction, possibly inside presentation-only wrappers."""
    return _local(_unwrap_presentation(el).tag) == "mfrac"


def _math_children(el: ET.Element) -> list[str]:
    return [_math_to_text(c) for c in el]


def _math_to_text(el: ET.Element) -> str:
    """Convert MathML to linear text, e.g. 2^(t/4), log_3(81), sqrt(x), (a)/(b).

    Tokens (mi/mn/mo/mtext) become their text; sup/sub/frac/roots become
    ^ _ / sqrt() root(); unknown elements just concatenate their children.
    """
    name = _local(el.tag)
    if name in {"mi", "mn", "mo", "mtext"}:
        return "".join(el.itertext())
    if name == "mspace":
        return " "
    kids = _math_children(el)
    if name == "msup" and len(kids) == 2:
        exponent = kids[1].strip()
        if exponent and all(ch in _PRIME_CHARS for ch in exponent):
            return f"{_wrap(el[0], kids[0])}{exponent}"  # g'(x), not g^(')(x)
        return f"{_wrap(el[0], kids[0])}^{_wrap(el[1], kids[1])}"
    if name == "msub" and len(kids) == 2:
        return f"{_wrap(el[0], kids[0])}_{_wrap(el[1], kids[1])}"
    if name == "msubsup" and len(kids) == 3:
        return f"{_wrap(el[0], kids[0])}_{_wrap(el[1], kids[1])}^{_wrap(el[2], kids[2])}"
    if name == "mfrac" and len(kids) == 2:
        return f"{_wrap(el[0], kids[0])}/{_wrap(el[1], kids[1])}"
    if name == "msqrt":
        return f"sqrt({''.join(kids)})"
    if name == "mroot" and len(kids) == 2:
        return f"root({kids[0]}, {kids[1]})"
    if name == "mtr":
        return " ".join(k for k in kids if k.strip())
    if name == "mtable":
        return "; ".join(k for k in kids if k.strip())
    if name == "mrow":
        out: list[str] = []
        for i, child in enumerate(el):
            text = kids[i]
            if _is_frac(child):
                prev = out[-1] if out else ""
                nxt = kids[i + 1] if i + 1 < len(kids) else ""
                # (1/2)ln(x), not 1/2ln(x): keep implicit multiplication unambiguous
                if nxt[:1].isalnum() or nxt[:1] == "(" or prev[-1:].isalnum() or prev[-1:] == ")":
                    text = f"({text})"
            out.append(text)
        return "".join(out)
    return "".join(kids)  # mtd, math, and anything unrecognised


def _linearize_math(math_el: ET.Element) -> str:
    """Faithful linear text for one <math> element, e.g. n(6)=1000·2^(6/4)≈2828."""
    return " ".join(_math_to_text(math_el).split())


# Empty <link target-id="..."/> elements get their text ("Figure 1.5") generated by
# OpenStax's renderer, so the XML has nothing there. Say what kind of thing it points at.
_REF_WORDS = {"figure": "Figure", "table": "Table", "example": "Example",
              "equation": "Equation", "exercise": "Exercise", "section": "Section"}


def _link_placeholder(link: ET.Element, refs: dict[str, str] | None) -> str:
    word = _REF_WORDS.get((refs or {}).get(link.get("target-id") or "", ""))
    return f"[{word}]" if word else ""


class _MathText:
    """Normalize XML text while retaining exact source-equation positions."""

    def __init__(self):
        self.parts: list[str] = []
        self.length = 0
        self.pending_space = False
        self.equations: list[EquationSpan] = []

    @property
    def text(self) -> str:
        return "".join(self.parts)

    def append(self, text: str) -> None:
        words = text.split()
        if not words:
            self.pending_space = self.pending_space or bool(text)
            return
        if self.length and (self.pending_space or text[0].isspace()):
            self.parts.append(" ")
            self.length += 1
        normalized = " ".join(words)
        self.parts.append(normalized)
        self.length += len(normalized)
        self.pending_space = text[-1].isspace()

    def append_equation(self, text: str) -> None:
        if text:
            self.append(text)
            self.equations.append(EquationSpan(text, self.length - len(text), self.length))


def _text_with_math(el: ET.Element, refs: dict[str, str] | None = None,
                    result: _MathText | None = None) -> _MathText:
    """Render text and source equations into one normalized coordinate system."""
    if result is None:
        result = _MathText()
    if el.tag == MATH_TAG:
        result.append_equation(_linearize_math(el))
        return result
    result.append(el.text or "")
    for child in el:
        if _local(child.tag) == "link" and not "".join(child.itertext()).strip():
            result.append(_link_placeholder(child, refs))
        else:
            _text_with_math(child, refs, result)
        result.append(child.tail or "")
    return result


def _block_text(el: ET.Element, refs: dict[str, str] | None = None) -> tuple[str, list[EquationSpan]]:
    """Plain text of a <para>/<equation>/<caption> block + equations found inside."""
    result = _text_with_math(el, refs)
    return result.text, result.equations


def _title_text(el: ET.Element, refs: dict[str, str] | None = None) -> str:
    """Title text with any math converted (e.g. "Differentiating x^3")."""
    return _text_with_math(el, refs).text


_BLOCKS = {"para", "equation"}
_SKIP = {"table", "media", "image", "newline", "colspec"}  # no usable text (tables: known gap)


def _has_blocks(el: ET.Element) -> bool:
    return any(_local(d.tag) in _BLOCKS for d in el.iter() if d is not el)


def _container_text(el: ET.Element, refs: dict[str, str] | None = None) -> tuple[str, list[EquationSpan]]:
    """Text of a whole example/exercise/list/note/definition as ONE block.

    Walks every descendant in document order so a problem and its solution
    stay together, e.g. "Bacterial Growth. Problem: ... Solution: ...".
    List items become "- item" (many items are plain text, not paragraphs) and
    a definition's term comes first ("term: meaning").
    """
    parts: list[tuple[str, list[EquationSpan]]] = []

    def leaf(node: ET.Element) -> None:
        text, eqs = _block_text(node, refs)
        if text:
            parts.append((text, eqs))

    def walk(node: ET.Element) -> None:
        for child in node:
            name = _local(child.tag)
            if name in _SKIP:
                continue
            if name in _BLOCKS:
                leaf(child)
            elif name == "title":
                title, eqs = _block_text(child, refs)
                if title:
                    parts.append((title + ".", eqs))
            elif name == "caption":
                text, eqs = _block_text(child, refs)
                if text:
                    prefix = "[Figure] "
                    parts.append((prefix + text, [eq.shifted(len(prefix)) for eq in eqs]))
            elif name in {"problem", "solution"}:
                parts.append((name.capitalize() + ":", []))
                walk(child)
            elif name == "item":
                parts.append(("-", []))
                mark = len(parts)
                walk(child) if _has_blocks(child) else leaf(child)
                if len(parts) == mark:
                    parts.pop()  # empty item: drop the bullet
            elif name == "term":
                text, eqs = _block_text(child, refs)
                if text:
                    parts.append((text + ":", eqs))
            elif name in {"figure", "list"} or _has_blocks(child):
                walk(child)
            else:
                leaf(child)  # plain-text element such as a label

    walk(el)
    equations: list[EquationSpan] = []
    offset = 0
    for text, eqs in parts:
        equations.extend(equation.shifted(offset) for equation in eqs)
        offset += len(text) + 1
    return " ".join(text for text, _ in parts), equations


# Authors sometimes leave a "Proof" <section> open and put the worked examples inside it,
# so "Proof" would label content that is not a proof. Leave it out of the section path.
_SKIP_SECTION_TITLES = {"proof"}
_CLASS_TITLES = {"section-exercises": "Exercises"}  # sections with no <title> element


def _section_path(parent: str, title: str) -> str:
    """'The Basic Rules' + 'The Constant Rule' -> 'The Basic Rules > The Constant Rule'."""
    if not title or title.lower() in _SKIP_SECTION_TITLES:
        return parent
    return f"{parent} > {title}" if parent else title


def parse_cnxml_string(xml_str: str, module_id: str, book_id: str, source: str = "osbooks") -> list[Chunk]:
    root = ET.fromstring(xml_str)
    ns = {"c": CNXML_NS, "md": MD_NS}

    title_el = root.find("c:title", ns)
    title = _title_text(title_el) if title_el is not None else module_id
    meta_id_el = root.find("c:metadata/md:content-id", ns)
    if meta_id_el is not None and (meta_id_el.text or "").strip():
        module_id = meta_id_el.text.strip()

    content_el = root.find("c:content", ns)
    if content_el is None:
        return []

    refs = {e.get("id"): _local(e.tag) for e in root.iter() if e.get("id")}

    # Walk content preserving section context: (section_path, block_text, equations)
    blocks: list[tuple[str, str, list[EquationSpan]]] = []

    def visit(parent: ET.Element, section: str) -> None:
        for child in parent:
            name = _local(child.tag)
            if name == "title":
                continue  # a section's title is applied by the section branch below
            elif name == "section":
                sec_title_el = child.find("c:title", ns)
                if sec_title_el is not None:
                    sec_title = _title_text(sec_title_el, refs)
                else:
                    sec_title = _CLASS_TITLES.get(child.get("class", ""), "")
                visit(child, _section_path(section, sec_title))
            elif name in {"para", "equation"}:
                text, eqs = _block_text(child, refs)
                if text:
                    blocks.append((section, text, eqs))
            elif name == "figure":
                for cap in child.findall("c:caption", ns):
                    text, eqs = _block_text(cap, refs)
                    if text:
                        prefix = "[Figure] "
                        blocks.append((section, prefix + text, [eq.shifted(len(prefix)) for eq in eqs]))
            elif name in {"list", "example", "exercise", "note", "definition", "rule"}:
                text, eqs = _container_text(child, refs)
                if text:
                    blocks.append((section, text, eqs))
            else:
                # Recurse into unknown containers (e.g. content root)
                if len(child):
                    visit(child, section)

    visit(content_el, "")
    glossary_el = root.find("c:glossary", ns)  # a sibling of <content>, so visit it separately
    if glossary_el is not None:
        visit(glossary_el, "Glossary")

    chunks: list[Chunk] = []
    for section, text, eqs in pack_blocks(blocks):
        pieces = [text] if len(text) <= MAX_CHARS else chunk_text(text, MAX_CHARS, OVERLAP)
        for i, piece in enumerate(pieces):
            start = i * (MAX_CHARS - OVERLAP)
            end = start + len(piece)
            chunks.append(
                Chunk(
                    book_id=book_id,
                    module_id=module_id,
                    title=title,
                    section=section,
                    text=piece,
                    equations=list(dict.fromkeys(
                        equation.text for equation in eqs
                        if start <= equation.start and equation.end <= end
                    )),
                    source=source,
                )
            )
    return chunks


def parse_cnxml_file(path: str, book_id: str) -> list[Chunk]:
    module_id = os.path.basename(os.path.dirname(path))
    with open(path, encoding="utf-8") as f:
        return parse_cnxml_string(f.read(), module_id, book_id)


def iter_module_files(bundle_root: str) -> list[str]:
    """All modules/<id>/index.cnxml under a cloned osbooks bundle."""
    out: list[str] = []
    modules_dir = os.path.join(bundle_root, "modules")
    if not os.path.isdir(modules_dir):
        return out
    for module_id in sorted(os.listdir(modules_dir)):
        p = os.path.join(modules_dir, module_id, "index.cnxml")
        if os.path.isfile(p):
            out.append(p)
    return out
